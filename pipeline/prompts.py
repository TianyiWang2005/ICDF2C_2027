"""All LLM prompts used in the pipeline (exported verbatim to prompts/ by export_prompts.py).

SAGE prompts follow the structure of the official implementation (github.com/phycholosogy/RAG-SAGE,
doing_protect.py): stage 1 = attribute extraction + generation from attributes, stage 2 = iterative refinement
between a privacy-evaluation agent and a rewriting agent that stops when the evaluator outputs THISISSAFE.
The official code only has prompts for chat/wiki/enron; the ECHR versions below are our adaptation.
"""

